local function pick(r, list)
  local total = 0
  for _, e in ipairs(list) do
    total = total + e[2]
  end
  local n = r(total)
  for _, e in ipairs(list) do
    n = n - e[2]
    if n <= 0 then
      return e[1]
    end
  end
end

