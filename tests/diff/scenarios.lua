-- 自分で書いた順を保ったまま { name, keys, config } にする
function M.fixed()
  local ret = {}
  for i, s in ipairs(fixed) do
    local keys, config
    if type(s) == "table" then
      keys, config = s[1], s[2]
    else
      keys = s
    end
    local label = keys
    if config and next(config) then
      label = label .. "  " .. vim.inspect(config, { newline = "", indent = "" })
    end
    ret[i] = { name = label, keys = keys, config = config or {} }
  end
  return ret
end

-- 小さな乱数（seed で決まる。LuaJIT の math.random に頼らない）
local function rng(seed)
  local state = seed % 2147483647
  if state <= 0 then
    state = state + 2147483646
  end
  return function(n)
    state = (state * 48271) % 2147483647
    return state % n + 1
  end
end

