---@param n integer
---@param seed integer
---@return table[]
function M.random(n, seed)
  local r = rng(seed)
  local ret = {}
  for i = 1, n do
    local len = 3 + r(14)
    local parts = {}
    for _ = 1, len do
      local k = r(12)
      if k <= 4 then
        -- 辞書にある語と、その後の操作
        parts[#parts + 1] = words[r(#words)] .. tails[r(#tails)]
      elseif k <= 6 then
        parts[#parts + 1] = pick(r, chunks)
      elseif k <= 8 then
        parts[#parts + 1] = starts[r(#starts)]
      elseif k == 9 then
        parts[#parts + 1] = okuri[r(#okuri)]
      else
        parts[#parts + 1] = pick(r, specials)
      end
    end
    if r(8) == 1 then
      parts[#parts + 1] = "<Esc>"
    end
    local keys = table.concat(parts)
    local config = configs[r(#configs)]
    ret[i] = { name = ("random #%d (seed %d)"):format(i, seed), keys = keys, config = config, random = true }
  end
  return ret
end

